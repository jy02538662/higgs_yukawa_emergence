print("="*72)
print("[严格化点1] S3 的 3-循环旋转角 = ±120°，是否唯一锁定 A2？")
print("  公式：s1*s2 旋转角 = 360° - 2*根夹角")
print("  +120° 旋转 -> 根夹角 120° -> Cartan [[2,-1],[-1,2]]（A2，非对角元 -1）")
print("  -120°(240°) -> 根夹角 60° -> Cartan [[2,1],[1,2]]（非对角元 +1）")
C_A2 = np.array([[2,-1],[-1,2]])
C_60 = np.array([[2,1],[1,2]])
print("  A2 Cartan 特征值:", np.round(np.linalg.eigvals(C_A2),3), " 正定、非对角元负 -> 有效")
print("  60° Cartan 特征值:", np.round(np.linalg.eigvals(C_60),3), " 正定但非对角元正")
print("  非对角元为正的 Cartan 不对应有限维 Lie 代数（Serre 关系不闭合）")
print("  => 60° 被自动排除，唯一有效 = A2（非对角元 -1）")

print("\n[严格化点2] 基本表示 3 = 2⊕1 是否结构匹配理论？")
print("  su(3) 基本表示 3（最高权 (1,0)），3 个权 = (1,0),(-1,1),(0,-1)")
print("  限制到 su(2)（l1,l2,l3 子代数，前 2x2 块）:")
print("    权 (1,0),(-1,1) -> 二重态 2（前两维颜色 1,2）")
print("    权 (0,-1) -> 单态 1（第三维颜色 3）")
print("  => 基本表示 3 = 2 ⊕ 1")
print("  理论的旋量 C^2（SU(2) 二重态，2 维）+ 相位 C（U(1) 单态，1 维）= 2 ⊕ 1")
print("  匹配是结构性的（旋量就是 2 维二重态，相位就是 1 维单态）")

print("\n[严格化点3] su(3) 的唯一 3 维不可约表示 = 基本表示 3？")
print("  su(3) 不可约表示维数: 3(基本), 3bar, 8(伴随), 6, 10, ...")
print("  唯一 3 维不可约 = 基本表示 3（最高权 (1,0)）")
print("  理论 C+C^2 是 3 维 => su(3) 作用其上 = 基本表示 3，自动（唯一）")

